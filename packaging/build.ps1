<#
.SYNOPSIS
  Build the frozen app (and the installer if Inno Setup is installed).
.DESCRIPTION
  Run from anywhere. Output: dist\Tsunami\ and packaging\Output\Tsunami-<version>-setup.exe.
  Signing: pass -Sign (needs TSUNAMI_SIGN_THUMBPRINT or TSUNAMI_PFX_PATH, see sign.ps1).
  Native commands do not stop PowerShell on failure, so every one is checked.
#>
param(
    [switch]$Sign,
    [switch]$SkipInstaller
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root

function Assert-Ok([string]$what) {
    if ($LASTEXITCODE -ne 0) { Write-Error "$what failed with exit code $LASTEXITCODE"; exit 1 }
}

# Windowed exes return immediately from a plain call, so wait and read the exit code.
function Invoke-Exe([string]$exe, [string[]]$exeArgs) {
    $p = Start-Process -FilePath $exe -ArgumentList $exeArgs -Wait -PassThru -NoNewWindow
    if ($p.ExitCode -ne 0) { Write-Error "$exe $exeArgs failed with exit code $($p.ExitCode)"; exit 1 }
}

uv sync --locked --group build
Assert-Ok 'uv sync'

# The version resource is regenerated by the spec; make it here too so a stale file is visible.
uv run python packaging/make_version_info.py
Assert-Ok 'make_version_info'
if (-not (Test-Path src\tsunami\gui\assets\tsunami.ico)) {
    uv run python packaging/make_icon.py
    Assert-Ok 'make_icon'
}

uv run pyinstaller packaging/tsunami.spec --noconfirm --clean --distpath dist --workpath build
Assert-Ok 'pyinstaller'

$gui = Join-Path $root 'dist\Tsunami\tsunami.exe'
$mcp = Join-Path $root 'dist\Tsunami\tsunami-mcp.exe'
Invoke-Exe $mcp @('--selftest')
Invoke-Exe $gui @('--selftest')   # windowed: only the exit code is visible
Write-Host 'Frozen self-tests passed.'

$version = (uv run python -c "from tsunami import __version__; print(__version__)").Trim()
Assert-Ok 'read version'

if ($Sign) {
    & "$PSScriptRoot\sign.ps1" -Files $gui,$mcp
    Assert-Ok 'sign exes'
}

if (-not $SkipInstaller) {
    $iscc = Get-Command ISCC.exe -ErrorAction SilentlyContinue
    $candidates = @(
        "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe",
        "$env:ProgramFiles\Inno Setup 6\ISCC.exe",
        "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe"
    )
    $isccPath = if ($iscc) { $iscc.Source } else { $candidates | Where-Object { Test-Path $_ } | Select-Object -First 1 }
    if ($isccPath) {
        & $isccPath "/DAppVersion=$version" packaging\installer.iss
        Assert-Ok 'ISCC'
        $setup = "packaging\Output\Tsunami-$version-setup.exe"
        if ($Sign) {
            & "$PSScriptRoot\sign.ps1" -Files $setup
            Assert-Ok 'sign installer'
        }
        Write-Host "Installer: $setup"
    } else {
        Write-Host 'Inno Setup 6 (ISCC.exe) not found; skipping the installer.'
    }
}
Write-Host 'Build complete: dist\Tsunami'
